#include <iostream>
using namespace std;

int main() {
    int age = 18;
    float marks = 85.5;
    char grade = 'A';
    const int year = 2026;

    cout << "Age: " << age << endl;
    cout << "Marks: " << marks << endl;
    cout << "Grade: " << grade << endl;
    cout << "Year: " << year << endl;

    int a = 10, b = 5;

    cout << "Addition: " << a + b << endl;
    cout << "Subtraction: " << a - b << endl;
    cout << "Multiplication: " << a * b << endl;

    return 0;
}